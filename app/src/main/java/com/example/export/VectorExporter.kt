package com.example.export

import android.content.Context
import android.content.Intent
import android.graphics.*
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.example.model.*
import com.example.pathfinder.PathfinderOps
import java.io.File
import java.io.FileOutputStream
import kotlin.math.roundToInt

object VectorExporter {

    enum class ExportFormat(val extension: String, val mimeType: String) {
        SVG("svg", "image/svg+xml"),
        PDF("pdf", "application/pdf"),
        PNG("png", "image/png"),
        JPEG("jpg", "image/jpeg"),
        WEBP("webp", "image/webp")
    }

    data class ExportConfig(
        val format: ExportFormat = ExportFormat.PNG,
        val ppi: Int = 300,
        val scale: Float = 1.0f,
        val includeBleed: Boolean = true,
        val includeCropMarks: Boolean = true,
        val softProofCmyk: Boolean = false,
        val artboardId: String? = null
    )

    data class ExportResult(
        val file: File,
        val widthPx: Int,
        val heightPx: Int,
        val fileSizeFormatted: String
    )

    /**
     * Calculates pixel dimensions for an artboard at given PPI and scale
     */
    fun calculatePixelSize(artboard: Artboard, ppi: Int, scale: Float): Pair<Int, Int> {
        val widthInches = artboard.width / 72f
        val heightInches = artboard.height / 72f
        val widthPx = (widthInches * ppi * scale).roundToInt().coerceAtLeast(1)
        val heightPx = (heightInches * ppi * scale).roundToInt().coerceAtLeast(1)
        return Pair(widthPx, heightPx)
    }

    fun estimateMemoryMb(widthPx: Int, heightPx: Int): Float {
        val bytes = widthPx.toLong() * heightPx.toLong() * 4L
        return bytes / (1024f * 1024f)
    }

    /**
     * Main export function
     */
    fun exportDocument(
        context: Context,
        document: Document,
        config: ExportConfig
    ): ExportResult {
        val exportDir = File(context.cacheDir, "exports").apply { mkdirs() }
        val sanitizedName = document.name.replace("\\s+".toRegex(), "_")
        val outputFile = File(exportDir, "${sanitizedName}_${System.currentTimeMillis()}.${config.format.extension}")

        val artboard = document.artboards.find { it.id == config.artboardId } ?: document.activeArtboard()
        val (wPx, hPx) = calculatePixelSize(artboard, config.ppi, config.scale)

        when (config.format) {
            ExportFormat.SVG -> {
                val svgContent = generateSvg(document, artboard, config)
                outputFile.writeText(svgContent)
            }
            ExportFormat.PDF -> {
                generatePdf(outputFile, document, artboard, config)
            }
            ExportFormat.PNG, ExportFormat.JPEG, ExportFormat.WEBP -> {
                generateBitmap(outputFile, document, artboard, config, wPx, hPx)
            }
        }

        val sizeKb = outputFile.length() / 1024f
        val formattedSize = if (sizeKb > 1024) "%.2f MB".format(sizeKb / 1024f) else "%.1f KB".format(sizeKb)
        return ExportResult(outputFile, wPx, hPx, formattedSize)
    }

    /**
     * Triggers the Android Native Share sheet
     */
    fun shareFile(context: Context, file: File, mimeType: String, title: String = "Share Artwork") {
        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(intent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        })
    }

    // --- SVG GENERATION ---
    private fun generateSvg(document: Document, artboard: Artboard, config: ExportConfig): String {
        val sb = StringBuilder()
        sb.appendLine("""<?xml version="1.0" encoding="UTF-8" standalone="no"?>""")
        sb.appendLine("""<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" """)
        sb.appendLine("""  width="${artboard.width}pt" height="${artboard.height}pt" """)
        sb.appendLine("""  viewBox="0 0 ${artboard.width} ${artboard.height}">""")
        sb.appendLine("""  <!-- Generated by Vertor Phics Pro - ColorMode: ${document.colorMode.name} -->""")

        // Defs for gradients
        sb.appendLine("""  <defs>""")
        var gradIndex = 0
        for (layer in document.layers) {
            for (element in layer.elements) {
                if (element.fill is VpPaint.Linear) {
                    val lin = element.fill as VpPaint.Linear
                    val id = "grad_${element.id.take(8)}_fill"
                    sb.appendLine("""    <linearGradient id="$id" x1="0%" y1="0%" x2="100%" y2="100%">""")
                    for (stop in lin.stops) {
                        val c = ColorEngine.toComposeColor(stop.color, document.profile)
                        val hex = ColorEngine.toHex((c.red * 255).roundToInt(), (c.green * 255).roundToInt(), (c.blue * 255).roundToInt())
                        sb.appendLine("""      <stop offset="${(stop.offset * 100).roundToInt()}%" stop-color="$hex" stop-opacity="${stop.color.alpha}"/>""")
                    }
                    sb.appendLine("""    </linearGradient>""")
                }
            }
        }
        sb.appendLine("""  </defs>""")

        // Background
        sb.appendLine("""  <rect width="${artboard.width}" height="${artboard.height}" fill="#FFFFFF"/>""")

        // Layers
        for (layer in document.layers) {
            if (!layer.visible) continue
            sb.appendLine("""  <g id="${layer.name.replace("\"", "")}">""")
            for (el in layer.elements) {
                if (el.isHidden) continue
                appendElementSvg(sb, el, document)
            }
            sb.appendLine("""  </g>""")
        }

        sb.appendLine("""</svg>""")
        return sb.toString()
    }

    private fun appendElementSvg(sb: StringBuilder, element: VectorElement, document: Document) {
        val fillStr = when (val f = element.fill) {
            is VpPaint.Solid -> {
                val c = ColorEngine.toComposeColor(f.color, document.profile)
                ColorEngine.toHex((c.red * 255).roundToInt(), (c.green * 255).roundToInt(), (c.blue * 255).roundToInt())
            }
            is VpPaint.Linear -> "url(#grad_${element.id.take(8)}_fill)"
            else -> "none"
        }
        val strokeStr = when (val s = element.stroke) {
            is VpPaint.Solid -> {
                val c = ColorEngine.toComposeColor(s.color, document.profile)
                ColorEngine.toHex((c.red * 255).roundToInt(), (c.green * 255).roundToInt(), (c.blue * 255).roundToInt())
            }
            else -> "none"
        }
        val strokeW = element.strokeStyle.width

        when (element) {
            is ShapeElement -> {
                val b = element.bounds
                when (element.shapeType) {
                    ShapeType.RECTANGLE -> {
                        sb.appendLine("""    <rect x="${b.left}" y="${b.top}" width="${b.width}" height="${b.height}" fill="$fillStr" stroke="$strokeStr" stroke-width="$strokeW" opacity="${element.opacity}"/>""")
                    }
                    ShapeType.ROUNDED_RECT -> {
                        sb.appendLine("""    <rect x="${b.left}" y="${b.top}" width="${b.width}" height="${b.height}" rx="${element.cornerRadius}" fill="$fillStr" stroke="$strokeStr" stroke-width="$strokeW" opacity="${element.opacity}"/>""")
                    }
                    ShapeType.ELLIPSE -> {
                        sb.appendLine("""    <ellipse cx="${b.centerX}" cy="${b.centerY}" rx="${b.width / 2f}" ry="${b.height / 2f}" fill="$fillStr" stroke="$strokeStr" stroke-width="$strokeW" opacity="${element.opacity}"/>""")
                    }
                    else -> {
                        appendPathSegmentsSvg(sb, element.toPathSegments(), true, fillStr, strokeStr, strokeW, element.opacity)
                    }
                }
            }
            is PathElement -> {
                appendPathSegmentsSvg(sb, element.segments, element.closed, fillStr, strokeStr, strokeW, element.opacity)
            }
            is TextElement -> {
                sb.appendLine("""    <text x="${element.x}" y="${element.y}" font-size="${element.fontSize}" font-family="${element.fontFamily}" fill="$fillStr" opacity="${element.opacity}">${element.text}</text>""")
            }
            is GroupElement -> {
                sb.appendLine("""    <g opacity="${element.opacity}">""")
                for (child in element.children) {
                    appendElementSvg(sb, child, document)
                }
                sb.appendLine("""    </g>""")
            }
        }
    }

    private fun appendPathSegmentsSvg(
        sb: StringBuilder,
        segments: List<PathSegment>,
        closed: Boolean,
        fill: String,
        stroke: String,
        strokeWidth: Float,
        opacity: Float
    ) {
        if (segments.isEmpty()) return
        val d = StringBuilder("M ${segments[0].anchor.x} ${segments[0].anchor.y}")
        for (i in 1 until segments.size) {
            val prev = segments[i - 1]
            val curr = segments[i]
            val cp1 = prev.absoluteOutHandle
            val cp2 = curr.absoluteInHandle
            val ep = curr.anchor
            if (prev.hasOutHandle() || curr.hasInHandle()) {
                d.append(" C ${cp1.x} ${cp1.y}, ${cp2.x} ${cp2.y}, ${ep.x} ${ep.y}")
            } else {
                d.append(" L ${ep.x} ${ep.y}")
            }
        }
        if (closed) {
            d.append(" Z")
        }
        sb.appendLine("""    <path d="$d" fill="$fill" stroke="$stroke" stroke-width="$strokeWidth" opacity="$opacity"/>""")
    }

    // --- PDF GENERATION ---
    private fun generatePdf(outputFile: File, document: Document, artboard: Artboard, config: ExportConfig) {
        val pdfDocument = PdfDocument()

        val bleedMargin = if (config.includeBleed) artboard.bleed.top.coerceAtLeast(18f) else 0f
        val cropMargin = if (config.includeCropMarks) 24f else 0f
        val totalMargin = bleedMargin + cropMargin

        val pageWidth = (artboard.width + totalMargin * 2).roundToInt()
        val pageHeight = (artboard.height + totalMargin * 2).roundToInt()

        val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas = page.canvas

        // Background
        val bgPaint = Paint().apply { color = Color.WHITE }
        canvas.drawRect(0f, 0f, pageWidth.toFloat(), pageHeight.toFloat(), bgPaint)

        // Draw crop marks if selected
        if (config.includeCropMarks) {
            val markPaint = Paint().apply {
                color = Color.BLACK
                strokeWidth = 0.5f
                style = Paint.Style.STROKE
            }
            val markLen = 14f
            val abL = totalMargin
            val abT = totalMargin
            val abR = totalMargin + artboard.width
            val abB = totalMargin + artboard.height

            // Top-left
            canvas.drawLine(abL - markLen - 4, abT, abL - 4, abT, markPaint)
            canvas.drawLine(abL, abT - markLen - 4, abL, abT - 4, markPaint)
            // Top-right
            canvas.drawLine(abR + 4, abT, abR + markLen + 4, abT, markPaint)
            canvas.drawLine(abR, abT - markLen - 4, abR, abT - 4, markPaint)
            // Bottom-left
            canvas.drawLine(abL - markLen - 4, abB, abL - 4, abB, markPaint)
            canvas.drawLine(abL, abB + 4, abL, abB + markLen + 4, markPaint)
            // Bottom-right
            canvas.drawLine(abR + 4, abB, abR + markLen + 4, abB, markPaint)
            canvas.drawLine(abR, abB + 4, abR, abB + markLen + 4, markPaint)

            // Press annotations
            val textPaint = Paint().apply {
                color = Color.DKGRAY
                textSize = 7f
                isAntiAlias = true
            }
            canvas.drawText("${document.name} | ${document.colorMode} (${document.profile.displayName}) | Bleed: 3mm", abL, abT - 10f, textPaint)
        }

        // Translate to artboard origin
        canvas.save()
        canvas.translate(totalMargin, totalMargin)

        // Render scene
        renderSceneToCanvas(canvas, document, config.softProofCmyk)

        canvas.restore()
        pdfDocument.finishPage(page)

        FileOutputStream(outputFile).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()
    }

    // --- BITMAP GENERATION (PNG / JPEG / WEBP) with safe memory scaling ---
    private fun generateBitmap(
        outputFile: File,
        document: Document,
        artboard: Artboard,
        config: ExportConfig,
        wPx: Int,
        hPx: Int
    ) {
        // Enforce safe ceiling to avoid OOM crash on mobile devices
        val maxDim = 4096
        val actualW = if (wPx > maxDim || hPx > maxDim) {
            val ratio = maxDim.toFloat() / maxOf(wPx, hPx)
            (wPx * ratio).roundToInt()
        } else {
            wPx
        }
        val actualH = if (wPx > maxDim || hPx > maxDim) {
            val ratio = maxDim.toFloat() / maxOf(wPx, hPx)
            (hPx * ratio).roundToInt()
        } else {
            hPx
        }

        val bitmap = Bitmap.createBitmap(actualW, actualH, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)

        // Clear background
        val bgPaint = Paint().apply {
            color = if (config.format == ExportFormat.JPEG) Color.WHITE else Color.TRANSPARENT
        }
        canvas.drawRect(0f, 0f, actualW.toFloat(), actualH.toFloat(), bgPaint)

        // Scale canvas to match target PPI and artboard bounds
        val scaleX = actualW.toFloat() / artboard.width
        val scaleY = actualH.toFloat() / artboard.height
        canvas.scale(scaleX, scaleY)

        // Render artwork
        renderSceneToCanvas(canvas, document, config.softProofCmyk)

        val compressFormat = when (config.format) {
            ExportFormat.JPEG -> Bitmap.CompressFormat.JPEG
            ExportFormat.WEBP -> Bitmap.CompressFormat.WEBP
            else -> Bitmap.CompressFormat.PNG
        }

        FileOutputStream(outputFile).use { out ->
            bitmap.compress(compressFormat, 95, out)
        }
        bitmap.recycle()
    }

    private fun renderSceneToCanvas(canvas: Canvas, document: Document, softProof: Boolean) {
        for (layer in document.layers) {
            if (!layer.visible) continue
            for (element in layer.elements) {
                if (element.isHidden) continue
                drawElement(canvas, element, document, softProof)
            }
        }
    }

    private fun drawElement(canvas: Canvas, element: VectorElement, document: Document, softProof: Boolean) {
        val androidPath = PathfinderOps.toAndroidPath(element)

        // Fill
        when (val f = element.fill) {
            is VpPaint.Solid -> {
                val c = ColorEngine.toComposeColor(f.color, document.profile, softProof)
                val paint = Paint().apply {
                    color = Color.argb(
                        (c.alpha * element.opacity * 255).roundToInt(),
                        (c.red * 255).roundToInt(),
                        (c.green * 255).roundToInt(),
                        (c.blue * 255).roundToInt()
                    )
                    style = Paint.Style.FILL
                    isAntiAlias = true
                }
                canvas.drawPath(androidPath, paint)
            }
            is VpPaint.Linear -> {
                val box = element.getBoundingBox()
                val colors = IntArray(f.stops.size)
                val positions = FloatArray(f.stops.size)
                for (i in f.stops.indices) {
                    val s = f.stops[i]
                    val sc = ColorEngine.toComposeColor(s.color, document.profile, softProof)
                    colors[i] = Color.argb((sc.alpha * 255).roundToInt(), (sc.red * 255).roundToInt(), (sc.green * 255).roundToInt(), (sc.blue * 255).roundToInt())
                    positions[i] = s.offset
                }
                val shader = LinearGradient(box.left, box.top, box.right, box.bottom, colors, positions, Shader.TileMode.CLAMP)
                val paint = Paint().apply {
                    this.shader = shader
                    style = Paint.Style.FILL
                    isAntiAlias = true
                    alpha = (element.opacity * 255).roundToInt()
                }
                canvas.drawPath(androidPath, paint)
            }
            else -> {}
        }

        // Stroke
        if (element.stroke !is VpPaint.None && element.strokeStyle.width > 0f) {
            val sc = when (val s = element.stroke) {
                is VpPaint.Solid -> ColorEngine.toComposeColor(s.color, document.profile, softProof)
                else -> androidx.compose.ui.graphics.Color.Black
            }
            val strokePaint = Paint().apply {
                color = Color.argb(
                    (sc.alpha * element.opacity * 255).roundToInt(),
                    (sc.red * 255).roundToInt(),
                    (sc.green * 255).roundToInt(),
                    (sc.blue * 255).roundToInt()
                )
                style = Paint.Style.STROKE
                strokeWidth = element.strokeStyle.width
                strokeCap = when (element.strokeStyle.cap) {
                    StrokeCap.ROUND -> Paint.Cap.ROUND
                    StrokeCap.SQUARE -> Paint.Cap.SQUARE
                    else -> Paint.Cap.BUTT
                }
                strokeJoin = when (element.strokeStyle.join) {
                    StrokeJoin.ROUND -> Paint.Join.ROUND
                    StrokeJoin.BEVEL -> Paint.Join.BEVEL
                    else -> Paint.Join.MITER
                }
                isAntiAlias = true
            }
            canvas.drawPath(androidPath, strokePaint)
        }

        // Text specific drawing
        if (element is TextElement) {
            val textPaint = Paint().apply {
                val c = when (val f = element.fill) {
                    is VpPaint.Solid -> ColorEngine.toComposeColor(f.color, document.profile, softProof)
                    else -> androidx.compose.ui.graphics.Color.White
                }
                color = Color.argb((c.alpha * element.opacity * 255).roundToInt(), (c.red * 255).roundToInt(), (c.green * 255).roundToInt(), (c.blue * 255).roundToInt())
                textSize = element.fontSize
                typeface = if (element.isBold) Typeface.DEFAULT_BOLD else Typeface.DEFAULT
                isAntiAlias = true
            }
            canvas.drawText(element.text, element.x, element.y, textPaint)
        }
    }
}
